test('configured identifier rules extract case IDs and serial numbers', () => {
  const found = extractIdentifiers({ subject: 'Case ID: tcm-1234', body: 'My serial no. ABCD1234EFGH is faulty. S/N: ZZZZ99998888.' }, DEFAULT_IDENTIFIER_RULES);
  assert.deepEqual(found.map(item => [item.type, item.value]), [['caseId', 'TCM-1234'], ['serialNumber', 'ABCD1234EFGH'], ['serialNumber', 'ZZZZ99998888']]);
  assert.deepEqual(extractIdentifiers({ subject: 'Hello', body: 'My phone is broken' }, DEFAULT_IDENTIFIER_RULES), []);
  // Disabled rules and broken patterns are skipped.
  assert.deepEqual(extractIdentifiers({ body: 'Case ID: X1234' }, [{ ...DEFAULT_IDENTIFIER_RULES[0], enabled: false }, { key: 'bad', type: 'caseId', pattern: '(', enabled: true }]), []);
  assert.throws(() => compileIdentifierRule({ type: 'caseId', pattern: '(' }), /not a valid regular expression/);
});

test('classification uses the inbox default, then whole-word keywords, and never guesses', () => {
  const rules = [{ category: 'Service', keywords: ['repair'], enabled: true }, { category: 'Retail', keywords: ['invoice', 'store'], enabled: true }];
  assert.equal(classifyEscalation({ inbox: { key: 'svc', defaultCategory: 'Retail' }, body: 'repair' }, rules).category, 'Retail');
  assert.deepEqual(classifyEscalation({ inbox: {}, body: 'Please repair my phone' }, rules), { category: 'Service', source: 'rule', matched: ['repair'], reason: null });
  assert.equal(classifyEscalation({ inbox: {}, body: 'Repair and invoice issue' }, rules).reason, 'ambiguous_category');
  assert.equal(classifyEscalation({ inbox: {}, body: 'restored settings' }, rules).reason, 'unclassified_category');
  assert.equal(classifyEscalation({ inbox: {}, body: 'anything' }, settings.classificationRules).reason, 'unclassified_category');
});

test('attachments: allowlisted types with matching content only', () => {
  const pdf = Buffer.from('%PDF-1.7 test');
  assert.equal(inspectAttachment({ filename: 'bill.pdf', content: pdf }, { maxBytes: 1000 }).ok, true);
  assert.equal(inspectAttachment({ filename: 'run.exe', content: Buffer.from('MZ') }, { maxBytes: 1000 }).rejectReason, 'type_not_allowed');
  assert.equal(inspectAttachment({ filename: 'photo.png', content: Buffer.from('<script>') }, { maxBytes: 1000 }).rejectReason, 'content_does_not_match_type');
  assert.equal(inspectAttachment({ filename: 'big.pdf', content: pdf }, { maxBytes: 4 }).rejectReason, 'too_large');
  assert.equal(inspectAttachment({ filename: 'none.pdf', content: null }, { maxBytes: 1000 }).rejectReason, 'content_unavailable');
  assert.equal(sanitiseFilename('../../etc/pass"wd‮.txt'), 'passwd.txt');
  assert.equal(sanitiseFilename('...hidden'), 'hidden');
});

test('templates fill known placeholders only and keep the reference in a one-line subject', () => {
  const rendered = renderTemplate({ subject: 'Hello {{customerName}} {{unknown}}', body: 'Ref {{reference}}\n{{message}}' }, { reference: 'B2C-2026-000001', customerName: 'A\r\nBcc: x@y.test', message: 'Line 1\nLine 2' });
  assert.equal(rendered.subject, '[B2C-2026-000001] Hello A Bcc: x@y.test');
  assert.doesNotMatch(rendered.subject, /[\r\n]/);
  assert.equal(rendered.body, 'Ref B2C-2026-000001\nLine 1\nLine 2');
});

test('redaction masks emails, phone numbers and secrets and drops message content', () => {
  assert.equal(redactText('Contact jane.doe@example.test or +91 98765 43210, Bearer abc.def'), 'Contact j***@example.test or [phone], Bearer [redacted]');
  assert.equal(redactText('client_secret=s3cr3t&x=1'), 'client_secret=[redacted]&x=1');
  assert.deepEqual(redactDetails({ body: 'secret text', error: 'failed for a@b.test', count: 2 }), { error: 'failed for a***@b.test', count: 2 });
});

// ---- Workflow permissions -------------------------------------------------------
const user = (id, b2cRole, b2cRegions = []) => ({ id, name: id, b2cRole, b2cRegions });
const admin = user('admin', 'b2c_admin');
const cm = user('cm', 'cluster_manager', ['North']);
const cmSouth = user('cm2', 'cluster_manager', ['South']);
const rbh = user('rbh', 'rbh');
const ticketAt = (status, extra = {}) => ({ status, region: 'North', participants: [], workflow: { path: ['cluster_manager', 'rbh', 'trainer'], currentLevel: 'cluster_manager', assignee: null }, validation: {}, ...extra });

test('visibility: admins see all, level staff see their level queue in their regions, others nothing', () => {
  const open = ticketAt(STATUS.OPEN);
  assert.equal(canView(open, admin), true);
  assert.equal(canView(open, cm), true);
  assert.equal(canView(open, cmSouth), false);
  assert.equal(canView(open, rbh), false);
  assert.equal(canView(open, { id: 'x', b2cRole: null }), false);
  assert.equal(canView(ticketAt(STATUS.TRIAGE), cm), false, 'triage is admin-only');
  assert.equal(canView(ticketAt(STATUS.CLOSED, { participants: ['rbh'] }), rbh), true, 'past participants keep read access');
  assert.deepEqual(visibilityFilter(admin), {});
  assert.equal(visibilityFilter(cm).$or.length, 4);
});

test('actions follow status and role: claim, accept, start, validation', () => {
  const open = ticketAt(STATUS.OPEN);
  assert.equal(canPerform('claim', { ticket: open, user: cm, settings }), true);
  assert.equal(canPerform('start', { ticket: open, user: cm, settings }), false);
  const assigned = ticketAt(STATUS.ASSIGNED, { workflow: { ...open.workflow, assignee: { userId: 'cm' } } });
  assert.deepEqual(allowedActions({ ticket: assigned, user: cm, settings }).sort(), ['accept', 'add_note', 'assign', 'request_clarification', 'reroute', 'retry_crm'].sort(), 'the engineer accepts before starting work');
  assert.equal(ACTIONS.escalate, undefined, 'escalation is automatic from the SLA, as for B2B tickets');
  const accepted = ticketAt(STATUS.ACCEPTED, { workflow: assigned.workflow });
  assert.equal(canPerform('start', { ticket: accepted, user: cm, settings }), true);
  assert.equal(canPerform('accept', { ticket: accepted, user: cm, settings }), false);
  assert.equal(canPerform('accept', { ticket: assigned, user: rbh, settings }), false, 'only the assignee accepts');
  assert.equal(canPerform('complete_triage', { ticket: ticketAt(STATUS.TRIAGE), user: admin, settings }), true);
  assert.equal(canPerform('close_unresolved', { ticket: assigned, user: cm, settings }), false);
  assert.equal(nextLevel(assigned, settings), 'rbh');
  assert.equal(validatorLevelFor(assigned, settings), 'rbh');
  assert.equal(validatorLevelFor(assigned, { ...settings, validation: { mode: 'none' } }), false);
  assert.equal(validatorLevelFor(assigned, { ...settings, validation: { mode: 'level', levelKey: 'trainer' } }), 'trainer');
  const pending = ticketAt(STATUS.PENDING_VALIDATION, { workflow: { ...open.workflow, assignee: { userId: 'cm' } }, validation: { validatorLevel: 'rbh', proposedBy: { userId: 'cm' } } });
  assert.equal(canPerform('approve_resolution', { ticket: pending, user: rbh, settings }), true);
  assert.equal(canPerform('approve_resolution', { ticket: pending, user: cm, settings }), false, 'no self-validation');
  const adminProposal = { ...pending, validation: { validatorLevel: null, proposedBy: { userId: 'admin' } } };
  assert.equal(canPerform('approve_resolution', { ticket: adminProposal, user: admin, settings }), false, 'admins cannot validate their own proposal either');
  assert.ok(Object.values(ACTIONS).every(action => action.statuses.length));
});

test('SLA escalation uses the B2B targets and rules: at risk, breached, critical level 3', () => {
  const rules = [
    { level: 1, trigger: 'SLA Approaching', priority: 'All', slaThreshold: 80 },
    { level: 2, trigger: 'SLA Breached', priority: 'All', slaThreshold: 100 },
    { level: 3, trigger: 'Critical SLA Breach', priority: 'Critical', slaThreshold: 100 },
  ];
  const createdAt = new Date('2026-10-01T00:00:00Z');
  const hours = value => createdAt.getTime() + value * 3600000;
  const ticket = (priority, extra = {}) => ({ status: 'In Progress', priority, createdAt, ...slaTargets(priority, createdAt), slaStatus: 'Healthy', escalationStatus: 'Not Escalated', escalationLevel: 0, ...extra });
  assert.equal(slaTargets('Medium', createdAt).resolutionTarget, '24 hours');
  assert.equal(computeSlaEscalation(ticket('Medium'), rules, hours(10)), null, 'healthy before 80%');
  const risk = computeSlaEscalation(ticket('Medium'), rules, hours(20));
  assert.deepEqual([risk.nextStatus, risk.level, risk.update.escalationStatus], ['At Risk', 1, 'At Risk']);
  const breach = computeSlaEscalation(ticket('Medium', risk.update), rules, hours(25));
  assert.deepEqual([breach.nextStatus, breach.level, breach.update.escalationStatus, breach.reason], ['SLA Breached', 2, 'Escalated', 'Resolution SLA exceeded']);
  assert.equal(computeSlaEscalation(ticket('Medium', breach.update), rules, hours(30)), null, 'no repeat once escalated');
  assert.equal(computeSlaEscalation(ticket('Critical'), rules, hours(5)).level, 3);
  assert.equal(computeSlaEscalation(ticket('Medium', { status: 'Completed' }), rules, hours(30)), null, 'completed tickets stop the clock');
});

test('settings validation rejects malformed configuration and stamps template approval', () => {
  assert.throws(() => validateSettingsUpdate({ identifierRules: [{ key: 'r', type: 'caseId', pattern: '(' }] }, settings), /valid regular expression/);
  assert.throws(() => validateSettingsUpdate({ inboxes: [{ key: 'a', address: 'a@x.test', provider: 'test' }] }, settings), /lowercase letters/);
  assert.throws(() => validateSettingsUpdate({ inboxes: [{ key: 'ab', address: 'bad', provider: 'test' }] }, settings), /valid email/);
  assert.throws(() => validateSettingsUpdate({ inboxes: [{ key: 'ab', address: 'a@x.test', provider: 'imap' }] }, settings), /unsupported provider/);
  assert.throws(() => validateSettingsUpdate({ workflowLevels: settings.workflowLevels.slice(1) }, settings), /each defined level/);
  assert.throws(() => validateSettingsUpdate({ validation: { mode: 'level', levelKey: 'nobody' } }, settings), /Choose the level/);
  const update = validateSettingsUpdate({ templates: [{ key: 'acknowledgement', subject: 'Received', body: 'Ref {{reference}}', approved: true }] }, settings, { name: 'Approver' });
  const ack = update.templates.find(item => item.key === 'acknowledgement');
  assert.equal(ack.approved, true);
  assert.equal(ack.approvedBy, 'Approver');
  assert.equal(update.templates.find(item => item.key === 'final_resolution').approved, false);
});

