test('Microsoft Graph adapter uses documented endpoints and maps messages', async () => {
  const calls = [];
  const json = (body, status = 200) => new Response(body === null ? null : JSON.stringify(body), { status, headers: { 'content-type': 'application/json' } });
  const fetchImpl = async (url, init = {}) => {
    calls.push({ url: String(url), method: init.method || 'GET', headers: init.headers || {}, body: init.body });
    if (String(url).startsWith('https://login.microsoftonline.com/tenant-1/oauth2/v2.0/token')) return json({ access_token: 'token-1', expires_in: 3600 });
    if (String(url).includes('/mailFolders/inbox/messages')) return json({ value: [{ id: 'AAMk1', internetMessageId: '<m1@x.test>', subject: 'Help', from: { emailAddress: { address: 'c@x.test', name: 'C' } }, toRecipients: [{ emailAddress: { address: 'inbox@x.test' } }], receivedDateTime: '2026-10-01T10:00:00Z', body: { contentType: 'text', content: 'Body' }, hasAttachments: true, internetMessageHeaders: [{ name: 'In-Reply-To', value: '<prev@x.test>' }, { name: 'Auto-Submitted', value: 'no' }, { name: 'Received', value: 'ignored' }] }] });
    if (String(url).endsWith('/attachments')) return json({ value: [{ '@odata.type': '#microsoft.graph.fileAttachment', name: 'a.pdf', contentType: 'application/pdf', size: 9, contentBytes: Buffer.from('%PDF-1.7').toString('base64') }, { '@odata.type': '#microsoft.graph.fileAttachment', name: 'logo.png', isInline: true }] });
    if (init.method === 'PATCH' || String(url).endsWith('/sendMail')) return new Response(null, { status: 202 });
    return json({ error: { code: 'NotFound' } }, 404);
  };
  const adapter = createMicrosoftGraphEmailAdapter({ tenantId: 'tenant-1', clientId: 'id', clientSecret: 'secret', fetchImpl });
  const inbox = { address: 'inbox@x.test' };
  const [message] = await adapter.fetchNew({ inbox, limit: 10 });
  assert.equal(message.providerMessageId, 'AAMk1');
  assert.equal(message.inReplyTo, '<prev@x.test>');
  assert.deepEqual(message.headers, { 'auto-submitted': 'no' });
  assert.equal(message.attachments.length, 1);
  assert.equal(message.attachments[0].content.toString(), '%PDF-1.7');
  const list = calls.find(call => call.url.includes('/mailFolders/inbox/messages'));
  assert.match(list.url, /^https:\/\/graph\.microsoft\.com\/v1\.0\/users\/inbox%40x\.test\/mailFolders\/inbox\/messages\?%24filter=isRead\+eq\+false/);
  assert.equal(list.headers.Authorization, 'Bearer token-1');
  await adapter.markProcessed({ inbox, providerMessageId: 'AAMk1' });
  await adapter.send({ inbox, to: 'c@x.test', subject: 'S', text: 'T', reference: 'B2C-2026-000001' });
  const sent = calls.find(call => call.url.endsWith('/sendMail'));
  assert.equal(JSON.parse(sent.body).message.body.contentType, 'Text');
  assert.equal(calls.filter(call => call.url.includes('oauth2')).length, 1, 'token is cached');
  const failing = createMicrosoftGraphEmailAdapter({ tenantId: 't', clientId: 'i', clientSecret: 's', fetchImpl: async () => json({ error: { code: 'TooManyRequests', message: 'contains c@x.test' } }, 429) });
  await assert.rejects(failing.fetchNew({ inbox }), error => error.retryable === true && !/c@x\.test/.test(error.message));
  await assert.rejects(createMicrosoftGraphEmailAdapter({}).fetchNew({ inbox }), error => error.retryable === false);
});

