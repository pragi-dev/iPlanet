const settings = defaultSettings({ testInboxAddress: 'escalations@b2c-inbox.test' });

test('HTML email is reduced to text without scripts, styles or markup', () => {
  const text = htmlToText('<html><head><style>p{}</style></head><body><p>Hello&nbsp;there</p><script>alert(1)</script><img src=x onerror=alert(1)>Line&#33;<br>Next &lt;b&gt;</body></html>');
  assert.doesNotMatch(text, /alert|style|onerror|<img|<script|<p>/);
  assert.match(text, /Hello there/);
  assert.match(text, /Line!\s*\nNext <b>/);
});

test('inbound email is normalised: control characters, bidi overrides and bad addresses removed', () => {
  const email = normaliseInboundEmail({ providerMessageId: 'm1', internetMessageId: 'garbage <abc@x.test> more', from: { address: ' Customer@Example.TEST ', name: 'A‮B\u0007' }, to: ['ok@x.test', 'not-an-address'], subject: 'Hi\r\nBcc: evil@x.test', text: 'Body\u0000 text' });
  assert.equal(email.from.address, 'customer@example.test');
  assert.equal(email.from.name, 'AB');
  assert.deepEqual(email.to, ['ok@x.test']);
  assert.equal(email.internetMessageId, '<abc@x.test>');
  assert.doesNotMatch(email.subject, /\n/);
  assert.equal(email.bodyText, 'Body text');
});

test('long bodies are truncated and flagged', () => {
  const email = normaliseInboundEmail({ providerMessageId: 'm', from: { address: 'a@b.test' }, text: 'x'.repeat(500) }, { maxBodyChars: 100 });
  assert.equal(email.bodyText.length, 100);
  assert.equal(email.bodyTruncated, true);
});

test('auto-replies, bulk mail and bounces are detected', () => {
  assert.equal(isAutoGenerated({ headers: { 'auto-submitted': 'auto-replied' } }), 'auto_submitted');
  assert.equal(isAutoGenerated({ headers: { 'auto-submitted': 'no' } }), null);
  assert.equal(isAutoGenerated({ headers: { precedence: 'bulk' } }), 'bulk_precedence');
  assert.equal(isAutoGenerated({ headers: { 'x-auto-response-suppress': 'All' } }), 'auto_reply_header');
  assert.equal(isAutoGenerated({ headers: {}, from: 'mailer-daemon@x.test' }), 'delivery_report');
  assert.equal(isAutoGenerated({ headers: {}, from: 'customer@x.test' }), null);
});

