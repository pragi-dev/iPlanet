test('assessDeviceRegion: exact serial match on the device records, explicit outcomes for every gap', () => {
  const serial = value => [{ type: 'serialNumber', value }];
  const device = (serialNumber, location) => ({ _id: `id-${serialNumber}`, serialNumber, model: 'Model X', location });
  const assess = (identifiers, devices) => assessDeviceRegion({ identifiers, devices });

  assert.deepEqual(assess(serial('abc12345'), [device('ABC12345', 'Chennai')]), { status: 'automatic', region: 'Chennai', source: 'device_location', reason: null, serialNumber: 'ABC12345', deviceId: 'id-ABC12345', model: 'Model X' });
  const outcome = (identifiers, devices = []) => { const result = assess(identifiers, devices); return [result.status, result.reason]; };
  assert.deepEqual(outcome(serial('ABC1234'), [device('ABC12345', 'Chennai')]), ['unresolved', 'serial_not_found'], 'no partial match');
  assert.deepEqual(outcome([{ type: 'caseId', value: 'C1' }]), ['unresolved', 'serial_number_missing']);
  assert.deepEqual(outcome([...serial('AAA11111'), ...serial('BBB22222')]), ['unresolved', 'multiple_serial_numbers']);
  assert.deepEqual(outcome([...serial('AAA11111'), ...serial('aaa11111')], [device('AAA11111', 'Pune')]), ['automatic', null], 'the same serial twice is one serial');
  assert.deepEqual(outcome(serial('-BAD')), ['unresolved', 'serial_number_invalid']);
  assert.deepEqual(outcome(serial('AAA11111'), [device('AAA11111', 'Pune'), device('aaa11111', 'Delhi')]), ['unresolved', 'multiple_device_matches']);
  assert.deepEqual(outcome(serial('AAA11111'), [device('AAA11111', '')]), ['unresolved', 'device_region_missing']);
  assert.equal(assess(serial('AAA11111'), [device('AAA11111', '')]).deviceId, 'id-AAA11111', 'the device found is kept for the reviewer');
});

