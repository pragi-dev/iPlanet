function fakeTransport({ fail } = {}) {
  const calls = { options: null, mails: [] };
  const createTransport = options => { calls.options = options; return { async sendMail(mail) { if (fail) throw fail; calls.mails.push(mail); return { messageId: mail.messageId, response: '250 2.0.0 Ok: queued as ABC123' }; } }; };
  return { calls, createTransport };
}

test('SMTP acknowledgement sender: company address, TLS, verified recipient, provider acceptance recorded', async () => {
  const { calls, createTransport } = fakeTransport();
  const sender = createSmtpAckSender(loadAckConfig(ackEnv), { createTransport });
  const result = await sender.send({ to: 'customer@example.test', replyTo: 'escalations@company.test', subject: 'Ticket [B2C-2026-000001]\r\nBcc: x@evil.test', text: 'Hello', messageId: '<id-1@sabora.local>' });
  assert.deepEqual(result, { providerMessageId: '<id-1@sabora.local>', responseCode: 250 });
  const [mail] = calls.mails;
  assert.deepEqual(mail.from, { name: 'Company SupportBcc: x@evil.test', address: 'noreply@company.test' });
  assert.deepEqual([mail.to, mail.replyTo, mail.subject, mail.text, mail.html], ['customer@example.test', 'escalations@company.test', 'Ticket [B2C-2026-000001] Bcc: x@evil.test', 'Hello', undefined], 'plain text; no line break reaches a header');
  assert.equal(mail.headers['Auto-Submitted'], 'auto-replied');
  assert.deepEqual([calls.options.host, calls.options.port, calls.options.secure, calls.options.requireTLS, calls.options.tls.minVersion, calls.options.auth.user], ['smtp.company.test', 465, true, false, 'TLSv1.2', 'noreply@company.test']);
  const starttls = fakeTransport();
  await createSmtpAckSender(loadAckConfig({ ...ackEnv, B2C_ACK_SMTP_PORT: '587' }), { createTransport: starttls.createTransport }).send({ to: 'customer@example.test', subject: 's', text: 't', messageId: '<id-2@x>' });
  assert.deepEqual([starttls.calls.options.secure, starttls.calls.options.requireTLS], [false, true], 'STARTTLS is required, never plain text');
});

test('SMTP acknowledgement sender: refuses bad input and classifies failures without leaking server replies', async () => {
  const send = (fail, env = ackEnv, to = 'customer@example.test') => createSmtpAckSender(loadAckConfig(env), fakeTransport({ fail })).send({ to, subject: 's', text: 't', messageId: '<m@x>' });
  await assert.rejects(send(null, ackEnv, 'customer@example.test\r\nBcc: x@evil.test'), { retryable: false, message: 'The recipient address is not valid.' });
  await assert.rejects(send(null, { ...ackEnv, B2C_ACK_SMTP_PASS: '' }), { retryable: false, message: /B2C_ACK_SMTP_PASS is not set/ });
  await assert.rejects(send(Object.assign(new Error('535 5.7.8 auth failed for secret-password'), { code: 'EAUTH', responseCode: 535 })), error => error.retryable === false && /SMTP login failed/.test(error.message) && !/secret/.test(error.message));
  await assert.rejects(send(Object.assign(new Error('550 mailbox unavailable'), { code: 'EENVELOPE', responseCode: 550 })), { retryable: false, message: 'The SMTP server refused the message (550).' });
  await assert.rejects(send(Object.assign(new Error('421 try later'), { code: 'EMESSAGE', responseCode: 421 })), { retryable: true, message: 'The SMTP server deferred the message (421).' });
  await assert.rejects(send(Object.assign(new Error('connect ETIMEDOUT'), { code: 'ETIMEDOUT' })), { retryable: true, message: 'Could not reach the SMTP server (ETIMEDOUT).' });
});

