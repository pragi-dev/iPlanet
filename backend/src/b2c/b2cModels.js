// The level before `level` on the path validates its work; at the first level, a B2C admin (null).
const assigningLevel = (path, level) => (path.indexOf(level) > 0 ? path[path.indexOf(level) - 1] : null);

// Resolutions were validated by the next level ('next_level'). Now the Service Executive's repair
// needs no approval and a repair the Cluster Manager did is approved by a B2C admin
// ('executive_direct'). Settings on an earlier rule move to it. A resolution already waiting for
// approval keeps waiting: one the Cluster Manager proposed goes to a B2C admin, and one the
// Service Executive proposed to the Cluster Manager who assigned it. Runs once per settings.
async function useExecutiveDirectValidation() {
  const { B2CSettings, B2CEscalation, B2CAuditEvent } = b2cModels;
  const changed = await B2CSettings.collection.updateMany({ 'validation.mode': { $in: ['next_level', 'previous_level'] } }, { $set: { 'validation.mode': 'executive_direct' } });
  if (!changed.modifiedCount) return;
  const waiting = await B2CEscalation.collection.find({ status: 'Pending Validation' }).toArray();
  for (const ticket of waiting) {
    const validator = assigningLevel(ticket.workflow?.path || [], ticket.workflow?.currentLevel);
    if ((ticket.validation?.validatorLevel ?? null) === validator) continue;
    await B2CEscalation.collection.updateOne({ _id: ticket._id }, { $set: { 'validation.validatorLevel': validator } });
    await B2CAuditEvent.create({ ticketId: ticket._id, action: 'validator_changed', actor: SYSTEM_ACTOR, fromStatus: ticket.status, toStatus: ticket.status, at: new Date(), details: { from: LEVEL_NAMES[ticket.validation?.validatorLevel] || 'B2C admin', to: validator ? LEVEL_NAMES[validator] : 'B2C admin' } });
  }
}

// Removed workflow levels (Regional Business Head, Trainer, CD Team AM) leave the settings, the
// staff who held them (who lose B2C access) and every ticket's path. An open ticket waiting at
// one returns to the Cluster Manager queue, and a resolution waiting for one to validate it goes
// to the level that assigned the ticket, or to a B2C admin. Safe to repeat: it finds nothing twice.
async function removeLevels(removed) {
  const { B2CSettings, B2CEscalation, B2CAuditEvent } = b2cModels;
  await B2CSettings.collection.updateMany({ 'workflowLevels.key': { $in: removed } }, { $pull: { workflowLevels: { key: { $in: removed } } } });
  await B2CSettings.collection.updateMany({ 'validation.levelKey': { $in: removed } }, { $set: { 'validation.mode': 'executive_direct', 'validation.levelKey': null } });
  await B2CSettings.db.collection('users').updateMany({ b2cRole: { $in: removed } }, { $set: { b2cRole: null } });
  const tickets = await B2CEscalation.collection.find({ $or: [{ 'workflow.path': { $in: removed } }, { 'workflow.currentLevel': { $in: removed } }, { 'validation.validatorLevel': { $in: removed } }] }).toArray();
  for (const ticket of tickets) {
    const kept = (ticket.workflow?.path || []).filter(key => !removed.includes(key));
    const path = kept.length ? kept : ['cluster_manager', 'service_excellence_lead'];
    const set = { 'workflow.path': path };
    const moved = removed.includes(ticket.workflow?.currentLevel);
    const level = moved ? path[0] : ticket.workflow?.currentLevel;
    if (moved) {
      set['workflow.currentLevel'] = level;
      // Work in progress at a removed level waits for a Cluster Manager to take it again.
      if (!['Pending Triage', 'Pending Validation', 'Completed', 'Closed'].includes(ticket.status)) Object.assign(set, { 'workflow.assignee': null, 'workflow.assignedAt': null, status: 'Open' });
    }
    if (removed.includes(ticket.validation?.validatorLevel)) set['validation.validatorLevel'] = assigningLevel(path, level);
    await B2CEscalation.collection.updateOne({ _id: ticket._id }, { $set: set });
    if (moved || set['validation.validatorLevel'] !== undefined) {
      const label = key => LEVEL_NAMES[key] || key;
      await B2CAuditEvent.create({
        ticketId: ticket._id, action: 'workflow_level_removed', actor: SYSTEM_ACTOR, fromStatus: ticket.status, toStatus: set.status || ticket.status, at: new Date(),
        details: { removedLevel: label(moved ? ticket.workflow.currentLevel : ticket.validation.validatorLevel), level: label(level), ...(set['validation.validatorLevel'] !== undefined ? { validator: set['validation.validatorLevel'] ? label(set['validation.validatorLevel']) : 'B2C admin' } : {}) },
      });
    }
  }
}
