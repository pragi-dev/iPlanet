import mongoose from 'mongoose';
import { CATEGORIES, IDENTIFIER_TYPES, STANDARD_PRIORITY, TEMPLATE_KEYS, UNCLASSIFIED } from './b2cDefaults.js';
import { slaTargets } from '../slaEscalation.js';

// B2C escalations live in their own collections. The B2B Ticket model carries
// company/device references, engineer transitions and an SLA engine that runs
// over every ticket, none of which apply to consumer email escalations.
const { ObjectId } = mongoose.Schema.Types;
const model = (name, schema) => mongoose.models[name] || mongoose.model(name, schema);

export const B2C_STATUSES = ['Pending Triage', 'Open', 'Engineer Assigned', 'Engineer Accepted', 'In Progress', 'Awaiting Customer', 'Pending Validation', 'Completed', 'Closed', 'Reopened'];
// Earlier status names, renamed on startup to the stages shared with B2B tickets.
const RENAMED_STATUSES = { Assigned: 'Engineer Assigned', Investigating: 'In Progress', Resolved: 'Completed' };

// ---- Settings (single document, key "default") ----------------------------------
const settingsSchema = new mongoose.Schema({
  key: { type: String, required: true, unique: true },
  inboxes: [{
    _id: false,
    key: { type: String, required: true, match: /^[a-z0-9-]{2,40}$/ },
    address: { type: String, required: true, lowercase: true, trim: true },
    displayName: { type: String, default: '' },
    provider: { type: String, enum: ['test', 'microsoft_graph'], required: true },
    defaultCategory: { type: String, enum: [...CATEGORIES, null], default: null },
    defaultRegion: { type: String, default: '' },
    enabled: { type: Boolean, default: true },
  }],
  identifierRules: [{ _id: false, key: String, type: { type: String, enum: IDENTIFIER_TYPES }, label: String, pattern: String, flags: { type: String, default: 'i' }, enabled: Boolean, confirmed: Boolean }],
  classificationRules: [{ _id: false, category: { type: String, enum: CATEGORIES }, keywords: [String], enabled: Boolean }],
  workflowLevels: [{ _id: false, key: String, label: String, order: Number, enabled: Boolean }],
  validation: { mode: { type: String, enum: ['next_level', 'level', 'none'], default: 'next_level' }, levelKey: { type: String, default: null } },
  templates: [{ _id: false, key: { type: String, enum: TEMPLATE_KEYS }, label: String, subject: String, body: String, approved: Boolean, approvedBy: String, approvedAt: Date }],
  updatedBy: String,
}, { timestamps: true });

// ---- Inbound email ----------------------------------------------------------------
const attachmentSchema = new mongoose.Schema({
  storageKey: String,
  filename: String,
  contentType: String,
  size: Number,
  sha256: String,
  status: { type: String, enum: ['stored', 'rejected'] },
  rejectReason: String,
}, { _id: false });

const inboundSchema = new mongoose.Schema({
  dedupeKey: { type: String, required: true, unique: true },
  inboxKey: { type: String, required: true },
  inboxAddress: String,
  provider: String,
  providerMessageId: { type: String, required: true },
  internetMessageId: String,
  inReplyTo: String,
  references: [String],
  from: { address: String, name: String },
  to: [String],
  cc: [String],
  subject: String,
  bodyText: String,
  bodyTruncated: Boolean,
  receivedAt: Date,
  // Why the message was treated as automated (auto-reply, bulk, bounce), or null.
  autoGenerated: { type: String, default: null },
  attachments: [attachmentSchema],
  status: { type: String, enum: ['received', 'processing', 'retrying', 'processed', 'ignored', 'failed'], default: 'received' },
  outcome: String,
  attempts: { type: Number, default: 0 },
  lastError: String,
  nextAttemptAt: Date,
  lockedUntil: Date,
  processedAt: Date,
  ticketId: { type: ObjectId, ref: 'B2CEscalation' },
}, { timestamps: true });
// The same message delivered to two TCM inboxes (e.g. cc'd) creates one ticket.
inboundSchema.index({ internetMessageId: 1 }, { unique: true, partialFilterExpression: { internetMessageId: { $type: 'string' } } });
inboundSchema.index({ status: 1, nextAttemptAt: 1 });
inboundSchema.index({ ticketId: 1, receivedAt: 1 });

// ---- Escalation ticket ----------------------------------------------------------
const personSchema = new mongoose.Schema({ userId: { type: ObjectId, ref: 'User', default: null }, name: String, email: String }, { _id: false });
const personRef = { type: personSchema, default: undefined };
const escalationSchema = new mongoose.Schema({
  reference: { type: String, required: true, unique: true },
  sourceEmailId: { type: ObjectId, ref: 'B2CInboundEmail' },
  inboxKey: String,
  inboxAddress: String,
  subject: String,
  summary: String,
  category: { type: String, enum: [...CATEGORIES, UNCLASSIFIED], default: UNCLASSIFIED },
  classification: { source: { type: String, enum: ['inbox', 'rule', 'manual', null], default: null }, matched: [String], note: String },
  identifiers: [{ _id: false, type: { type: String, enum: IDENTIFIER_TYPES }, value: String, ruleKey: String, source: String }],
  customer: { email: String, name: String, phone: String, crmCustomerId: String },
  devices: [{ _id: false, serialNumber: String, model: String, productName: String, purchaseDate: Date, warrantyStatus: String, crmDeviceId: String }],
  crmCases: [{ _id: false, caseId: String, status: String, openedAt: Date, description: String }],
  crm: { status: { type: String, enum: ['pending', 'not_configured', 'matched', 'no_match', 'multiple_matches', 'error'], default: 'pending' }, provider: String, mode: String, fetchedAt: Date, attempts: { type: Number, default: 0 }, lastError: String, matchCount: Number, nextAttemptAt: Date },
  region: { type: String, default: '' },
  status: { type: String, enum: B2C_STATUSES, default: 'Pending Triage' },
  // SLA and escalation, with the same fields and values as B2B service tickets. B2C has no
  // priority levels: every ticket gets the standard 24-hour target, and only the escalation
  // rules for all priorities apply.
  responseTarget: String,
  resolutionTarget: String,
  slaTargetAt: Date,
  slaStatus: { type: String, enum: ['Healthy', 'At Risk', 'Escalated', 'SLA Breached', 'Resolved'], default: 'Healthy' },
  escalationLevel: { type: Number, default: 0 },
  escalationStatus: { type: String, enum: ['Not Escalated', 'At Risk', 'Escalated', 'SLA Breached', 'Resolved'], default: 'Not Escalated' },
  escalationReason: String,
  escalatedAt: Date,
  triage: { reasons: [String], resolvedAt: Date, resolvedBy: String },
  workflow: { path: [String], currentLevel: { type: String, default: null }, assignee: personRef, assignedAt: Date },
  participants: [{ type: ObjectId, ref: 'User' }],
  validation: { validatorLevel: String, proposedBy: personRef, proposedAt: Date, resolutionSummary: String, customerMessage: String, decidedBy: personRef, decidedAt: Date, decision: String, rejectionReason: String },
  resolution: { summary: String, resolvedBy: personRef, resolvedAt: Date, finalMessageId: { type: ObjectId, ref: 'B2COutboundEmail' } },
  acknowledgement: { status: { type: String, enum: ['pending', 'queued', 'held', 'sent', 'failed', 'skipped'], default: 'pending' }, outboundId: { type: ObjectId, ref: 'B2COutboundEmail' }, sentAt: Date },
  reopenCount: { type: Number, default: 0 },
  closedAt: Date,
  closure: { reason: String, by: personRef },
  lastCustomerMessageAt: Date,
  lastActivityAt: Date,
}, { timestamps: true, optimisticConcurrency: true });
escalationSchema.index({ sourceEmailId: 1 }, { unique: true, partialFilterExpression: { sourceEmailId: { $type: 'objectId' } } });
escalationSchema.index({ status: 1, createdAt: -1 });
escalationSchema.index({ slaStatus: 1, status: 1 });
escalationSchema.index({ 'workflow.assignee.userId': 1, status: 1 });
escalationSchema.index({ 'workflow.currentLevel': 1, status: 1 });
escalationSchema.index({ category: 1, region: 1 });
escalationSchema.index({ 'customer.email': 1 });
escalationSchema.index({ 'crm.status': 1, 'crm.nextAttemptAt': 1 });

// ---- Audit trail (append only) ------------------------------------------------
const auditSchema = new mongoose.Schema({
  ticketId: { type: ObjectId, ref: 'B2CEscalation', index: true },
  reference: String,
  action: { type: String, required: true },
  actor: new mongoose.Schema({ userId: { type: ObjectId, ref: 'User', default: null }, name: String, role: String }, { _id: false }),
  fromStatus: String,
  toStatus: String,
  note: String,
  details: { type: Object, default: {} },
  at: { type: Date, default: Date.now },
});
auditSchema.index({ ticketId: 1, at: 1 });

// ---- Outbound email -------------------------------------------------------------
const outboundSchema = new mongoose.Schema({
  dedupeKey: { type: String, unique: true, sparse: true },
  ticketId: { type: ObjectId, ref: 'B2CEscalation', index: true },
  inboxKey: String,
  kind: { type: String, enum: ['acknowledgement', 'clarification', 'final', 'reply'] },
  templateKey: String,
  vars: { type: Object, default: {} },
  to: String,
  subject: String,
  bodyText: String,
  status: { type: String, enum: ['queued', 'held', 'retrying', 'sending', 'sent', 'failed'], default: 'queued' },
  heldReason: String,
  attempts: { type: Number, default: 0 },
  nextAttemptAt: Date,
  lockedUntil: Date,
  lastError: String,
  messageId: String,
  providerMessageId: String,
  mode: String,
  sentAt: Date,
  createdBy: personRef,
}, { timestamps: true });
outboundSchema.index({ status: 1, nextAttemptAt: 1 });
outboundSchema.index({ messageId: 1 }, { sparse: true });

// ---- Integration health ---------------------------------------------------------
const integrationStatusSchema = new mongoose.Schema({
  key: { type: String, required: true, unique: true },
  kind: { type: String, enum: ['email', 'crm', 'outbound', 'scheduler'] },
  label: String,
  provider: String,
  mode: { type: String, enum: ['test', 'live', 'not_configured', 'disabled'] },
  lastRunAt: Date,
  lastSuccessAt: Date,
  lastErrorAt: Date,
  lastError: String,
  consecutiveFailures: { type: Number, default: 0 },
  details: { type: Object, default: {} },
}, { timestamps: true });

const counterSchema = new mongoose.Schema({ key: { type: String, required: true, unique: true }, seq: { type: Number, default: 0 } });

export const B2CSettings = model('B2CSettings', settingsSchema);
export const B2CInboundEmail = model('B2CInboundEmail', inboundSchema);
export const B2CEscalation = model('B2CEscalation', escalationSchema);
export const B2CAuditEvent = model('B2CAuditEvent', auditSchema);
export const B2COutboundEmail = model('B2COutboundEmail', outboundSchema);
export const B2CIntegrationStatus = model('B2CIntegrationStatus', integrationStatusSchema);
export const B2CCounter = model('B2CCounter', counterSchema);

export const b2cModels = { B2CSettings, B2CInboundEmail, B2CEscalation, B2CAuditEvent, B2COutboundEmail, B2CIntegrationStatus, B2CCounter };

export async function ensureB2CIndexes() {
  await Promise.all(Object.values(b2cModels).map(item => item.createIndexes()));
  // Raw collection update: the old values are no longer in the schema enum.
  for (const [from, to] of Object.entries(RENAMED_STATUSES)) await b2cModels.B2CEscalation.collection.updateMany({ status: from }, { $set: { status: to } });
  // Tickets created before SLA tracking get the standard target from their creation time.
  const untracked = await b2cModels.B2CEscalation.collection.find({ slaTargetAt: { $exists: false } }, { projection: { createdAt: 1 } }).toArray();
  for (const ticket of untracked) await b2cModels.B2CEscalation.collection.updateOne({ _id: ticket._id, slaTargetAt: { $exists: false } }, { $set: { ...slaTargets(STANDARD_PRIORITY, ticket.createdAt), slaStatus: 'Healthy', escalationLevel: 0, escalationStatus: 'Not Escalated' } });
  // Priority levels were removed: drop any stored priority and return to the standard target.
  const prioritised = await b2cModels.B2CEscalation.collection.find({ priority: { $exists: true } }, { projection: { createdAt: 1 } }).toArray();
  for (const ticket of prioritised) await b2cModels.B2CEscalation.collection.updateOne({ _id: ticket._id }, { $unset: { priority: '' }, $set: slaTargets(STANDARD_PRIORITY, ticket.createdAt) });
}
