// Normalises an inbound email from any connector into plain, bounded text.
// Email content is untrusted: HTML is reduced to text here and is never
// stored or rendered as markup, control characters are removed, and every
// field has a length limit before any pattern runs over it.
const MAX_SUBJECT = 500;
const MAX_HEADER = 1000;
const EMAIL_ADDRESS = /^[^\s@<>()",;:]{1,64}@[A-Za-z0-9.-]{1,253}\.[A-Za-z]{2,63}$/;

const NAMED_ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', ndash: '–', mdash: '—', rsquo: '’', lsquo: '‘', rdquo: '”', ldquo: '“', hellip: '…', copy: '©', reg: '®', trade: '™' };

export function decodeEntities(text) {
  return text.replace(/&(#x[0-9a-f]{1,6}|#\d{1,7}|[a-z]{2,8});/gi, (match, code) => {
    if (code[0] === '#') {
      const point = code[1].toLowerCase() === 'x' ? Number.parseInt(code.slice(2), 16) : Number.parseInt(code.slice(1), 10);
      return Number.isInteger(point) && point > 0 && point <= 0x10ffff && !(point >= 0xd800 && point <= 0xdfff) ? String.fromCodePoint(point) : '';
    }
    return NAMED_ENTITIES[code.toLowerCase()] ?? match;
  });
}

// Removes control characters other than tab and newline, and bidi overrides
// that could disguise text in the portal.
export function stripControl(text) {
  return String(text ?? '').replace(/\r\n?/g, '\n').replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f‪-‮⁦-⁩]/g, '');
}

export function htmlToText(html, max = 200_000) {
  let text = String(html ?? '').slice(0, max * 2);
  text = text.replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/<(script|style|head|title|template|svg|object|iframe)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, ' ')
    .replace(/<br\s*\/?>/gi, '\n')
    .replace(/<\/(p|div|li|tr|h[1-6]|blockquote|table|section|article)\s*>/gi, '\n')
    .replace(/<li\b[^>]*>/gi, '\n• ')
    .replace(/<[^>]*>/g, ' ');
  return decodeEntities(text);
}

export function normaliseText(text, max) {
  const cleaned = stripControl(text)
    .replace(/[ \t ]+/g, ' ')
    .replace(/ *\n */g, '\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return { text: cleaned.slice(0, max), truncated: cleaned.length > max };
}

export function normaliseAddress(value) {
  const address = String(value ?? '').trim().replace(/^<|>$/g, '').toLowerCase();
  return EMAIL_ADDRESS.test(address) ? address : null;
}

function normaliseName(value) {
  return stripControl(value).replace(/\s+/g, ' ').trim().slice(0, 200);
}

const headerValue = (headers, name) => {
  const value = headers?.[name] ?? headers?.[name.toLowerCase()];
  return value === undefined || value === null ? '' : String(value).slice(0, MAX_HEADER);
};

const messageIdList = value => (String(value || '').match(/<[^<>\s]{1,250}>/g) || []).slice(0, 50);

// RFC 3834 auto-replies, bulk/list mail and bounces must not create tickets or
// receive acknowledgements, otherwise two auto-responders can loop forever.
export function isAutoGenerated({ headers = {}, from }) {
  const autoSubmitted = headerValue(headers, 'auto-submitted').toLowerCase();
  if (autoSubmitted && autoSubmitted !== 'no') return 'auto_submitted';
  if (/^(bulk|junk|list|auto_reply)$/i.test(headerValue(headers, 'precedence').trim())) return 'bulk_precedence';
  if (headerValue(headers, 'x-autoreply') || headerValue(headers, 'x-autorespond') || /\b(all|oof|autoreply)\b/i.test(headerValue(headers, 'x-auto-response-suppress'))) return 'auto_reply_header';
  if (/^(mailer-daemon|postmaster)@/i.test(from || '')) return 'delivery_report';
  return null;
}

export function ticketReferenceIn(subject, prefix) {
  const match = String(subject || '').match(new RegExp(`\\[(${prefix}-\\d{4}-\\d{6})\\]`));
  return match ? match[1] : null;
}

// `raw` is the connector's message shape (see connectors/emailConnector.js).
export function normaliseInboundEmail(raw, { maxBodyChars = 100_000 } = {}) {
  const headers = Object.fromEntries(Object.entries(raw.headers || {}).map(([key, value]) => [String(key).toLowerCase(), value]));
  const fromAddress = normaliseAddress(raw.from?.address);
  const textSource = raw.text && String(raw.text).trim() ? String(raw.text) : htmlToText(raw.html);
  const body = normaliseText(textSource, maxBodyChars);
  const list = values => (Array.isArray(values) ? values : []).map(normaliseAddress).filter(Boolean).slice(0, 50);
  return {
    providerMessageId: String(raw.providerMessageId || '').slice(0, 500),
    internetMessageId: messageIdList(raw.internetMessageId)[0] || null,
    inReplyTo: messageIdList(raw.inReplyTo)[0] || null,
    references: messageIdList(Array.isArray(raw.references) ? raw.references.join(' ') : raw.references),
    from: { address: fromAddress, name: normaliseName(raw.from?.name) },
    to: list(raw.to),
    cc: list(raw.cc),
    subject: normaliseText(raw.subject || '', MAX_SUBJECT).text.replace(/\n/g, ' '),
    bodyText: body.text,
    bodyTruncated: body.truncated,
    receivedAt: raw.receivedAt && !Number.isNaN(new Date(raw.receivedAt).getTime()) ? new Date(raw.receivedAt) : new Date(),
    autoGenerated: isAutoGenerated({ headers, from: fromAddress }),
  };
}
